    if ($states.Count -ne 1 -or $states[0] -cne $ExpectedState -or $codes.Count -ne 1 -or
        [string]::IsNullOrWhiteSpace($codes[0]) -or $fields['error']) {
        throw 'Missing, ambiguous or mismatched authorization response.'
    }
    return $codes[0]
}

