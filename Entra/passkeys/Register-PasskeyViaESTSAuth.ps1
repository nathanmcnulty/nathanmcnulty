        $code = Invoke-EntraRegistrationAuthorization -Context $Context -Uri $uri
        return Complete-EntraRegistrationTokenExchange -Context $Context -Authority $authority -Code $code -TenantId $TenantId
    } finally { $cookie = $null }
}

