BeforeAll {
    $root=Join-Path $PSScriptRoot '../PasskeyLogin.ps1'
    $kv=Join-Path $PSScriptRoot '../keyvault/PasskeyLogin.ps1'
}
Describe 'Generated public login files' {
    It 'keeps both original URLs as byte-identical self-contained files' {
        (Get-FileHash $root -Algorithm SHA256).Hash | Should -BeExactly (Get-FileHash $kv -Algorithm SHA256).Hash
        $text=Get-Content $root -Raw
        $text | Should -Match 'Generated by build/build.ps1'
        $text | Should -Not -Match 'Import-Module|Invoke-Expression'
        $text | Should -Match '^#Requires -Version 7\.6'
    }
    It 'preserves named inputs, credential/username aliases and pipeline support' {
        foreach($path in @($root,$kv)) {
            $command=Get-Command $path
            foreach($name in @('CredentialFromPipeline','KeyFilePath','UserPrincipalName','UserHandle','CredentialIdentifier','PrivateKey','RelyingParty','AuthUrl','UserAgent','Proxy','KeyVaultName','KeyVaultKeyName','KeyVaultAccessToken','KeyVaultClientId','KeyVaultClientSecret','KeyVaultTenantId','PassThru','IncludeAuthenticationCookie','PersistSessionToGlobalScope')) {
                $command.Parameters[$name] | Should -Not -BeNullOrEmpty
            }
            $command.Parameters.UserPrincipalName.Aliases | Should -Contain 'UserName'
            $command.Parameters.CredentialIdentifier.Aliases | Should -Contain 'CredentialId'
            ($command.Parameters.CredentialFromPipeline.Attributes | Where-Object {$_ -is [Management.Automation.ParameterAttribute]}).ValueFromPipeline | Should -BeTrue
        }
    }
}
