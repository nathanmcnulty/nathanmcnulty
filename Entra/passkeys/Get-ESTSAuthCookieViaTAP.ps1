function ConvertFrom-UuidToBase64Url {
    param([string]$Uuid)

    if ($Uuid -notmatch '^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$') {
        return $Uuid  # Not a UUID, return as-is
